/**
 * @zakkster/lite-o1 -- benchmark harness (shared measurement primitives).
 *
 * Repo-only dev/measurement infra. NOT part of the published tarball (not in
 * package.json files[]), NOT imported by O1.js, and NOT a data-structure member.
 * It profiles the nine shipped members against the JS built-ins across the eight
 * dimensions of RESEARCH.md section 3.
 *
 * The PRNG is the repo's own Numerical Recipes LCG (the one every *.test.js uses):
 *
 *     seed = (seed * 1664525 + 1013904223) >>> 0
 *
 * There is deliberately NO xorshift here -- every deterministic trace in this
 * suite is generated by this single LCG so the fixed-seed determinism gate
 * (two runs at seed DEFAULT_SEED -> byte-identical trace hashes) is meaningful.
 */

/** The fixed seed for the determinism gate: golden-ratio 32-bit constant. */
export const DEFAULT_SEED = 0x9e3779b1 >>> 0;

/**
 * The repo's Numerical Recipes LCG as a stateful generator. Returns a nullary
 * function that yields the next uint32 in the stream. Seed is coerced to uint32.
 * @param {number} [seed=DEFAULT_SEED]
 * @returns {() => number}
 */
export function prng(seed = DEFAULT_SEED) {
    let s = seed >>> 0;
    return function next() {
        s = (s * 1664525 + 1013904223) >>> 0;
        return s;
    };
}

/**
 * Median of a numeric sample set (median-of-9 by convention here: the suite times
 * 9 reps per point and reports this). Copies + sorts, so the input is untouched.
 * @param {ArrayLike<number>} samples
 * @returns {number}
 */
export function median(samples) {
    const a = Float64Array.from(samples);
    a.sort();
    const n = a.length;
    if (n === 0) return 0;
    const m = n >> 1;
    return (n & 1) ? a[m] : (a[m - 1] + a[m]) / 2;
}

/**
 * Two warm-up rounds (the suite convention): run `fn(i)` over `batch` iterations
 * `rounds` times, discarding the result, so V8 tiers up to optimized code and the
 * branch predictor + caches are primed before a measured pass.
 * @param {(i:number) => void} fn
 * @param {number} batch
 * @param {number} [rounds=2]
 */
export function warm(fn, batch, rounds = 2) {
    for (let r = 0; r < rounds; r++) {
        for (let i = 0; i < batch; i++) fn(i);
    }
}

/** True iff this process was started with --expose-gc (global.gc present). */
export function hasGc() {
    return typeof globalThis.gc === 'function';
}

/** Force a full GC when --expose-gc is available; a no-op otherwise. */
export function gcNow() {
    if (typeof globalThis.gc === 'function') globalThis.gc();
}

/**
 * Percentile of an ASCENDING-sorted numeric array via nearest-rank. p in [0, 100].
 * Returns 0 for an empty array (the vacuity gate rejects that separately).
 * @param {ArrayLike<number>} sortedAsc
 * @param {number} p
 * @returns {number}
 */
export function percentile(sortedAsc, p) {
    const n = sortedAsc.length;
    if (n === 0) return 0;
    let idx = Math.round((p / 100) * (n - 1));
    // Fail closed on a non-finite p (e.g. NaN): idx < / > comparisons are both
    // false for NaN, so without this guard `sortedAsc[NaN]` silently reads back
    // `undefined` instead of a number -- a vacuity gate would then have to catch
    // it downstream. Clamp to the low end instead.
    if (!Number.isFinite(idx)) idx = 0;
    if (idx < 0) idx = 0;
    if (idx > n - 1) idx = n - 1;
    return sortedAsc[idx];
}

/**
 * Time a hot op in ns/op over one micro-batch. Returns +Infinity if the batch was
 * too fast to register (dt === 0) so a caller can drop it; every real reading is a
 * finite positive number.
 * @param {(i:number) => void} op
 * @param {number} batch
 * @returns {number} nanoseconds per op
 */
export function timeNsPerOp(op, batch) {
    const t0 = performance.now();
    for (let i = 0; i < batch; i++) op(i);
    const dt = performance.now() - t0; // milliseconds
    return dt > 0 ? (dt * 1e6) / batch : Infinity;
}

/**
 * Collect `samples` ns/op readings, each over a `batch`-op micro-batch, after two
 * warm-up rounds. Returns a plain array (ascending unsorted); callers sort as
 * needed. Infinite (sub-tick) readings are replaced by the smallest finite one so
 * percentiles stay finite and positive.
 * @param {(i:number) => void} op
 * @param {number} batch
 * @param {number} samples
 * @returns {number[]}
 */
export function collect(op, batch, samples) {
    warm(op, batch, 2);
    const out = new Array(samples);
    let minFinite = Infinity;
    for (let s = 0; s < samples; s++) {
        const v = timeNsPerOp(op, batch);
        out[s] = v;
        if (v < minFinite) minFinite = v;
    }
    if (!isFinite(minFinite)) minFinite = 1e-3; // whole run was sub-tick
    for (let s = 0; s < samples; s++) if (!isFinite(out[s])) out[s] = minFinite;
    return out;
}

/**
 * A rolling 32-bit hash (for the fixed-seed determinism gate). Fold a workload's
 * emitted integers through this and compare two runs' final hashes.
 * @param {number} h    the running hash (start with 0x811c9dc5 for FNV-ish spread)
 * @param {number} x    the next integer to fold
 * @returns {number} the updated uint32 hash
 */
export function foldHash(h, x) {
    h = (h ^ (x | 0)) >>> 0;
    h = (Math.imul(h, 16777619)) >>> 0; // FNV-1a prime
    return h >>> 0;
}

/**
 * Dispersion of a sample set: median, mean, coefficient of variation, and a
 * stability verdict. cv = POPULATION stddev / mean (population, not sample: these
 * are exhaustive measured batches, not an inference from a smaller draw). stable
 * is cv < 0.05 (a 5% spread is the suite's "steady" bar). FAIL CLOSED: an empty
 * set or a non-positive mean returns { median:0, mean:0, cv:0, stable:false } --
 * NEVER NaN / Infinity, and NEVER a spurious `stable:true` on no evidence.
 * @param {ArrayLike<number>} samples
 * @returns {{median:number, mean:number, cv:number, stable:boolean}}
 */
export function stats(samples) {
    const n = samples.length;
    if (n === 0) return { median: 0, mean: 0, cv: 0, stable: false };
    let sum = 0;
    for (let i = 0; i < n; i++) sum += samples[i];
    const mean = sum / n;
    if (!(mean > 0)) return { median: 0, mean: 0, cv: 0, stable: false }; // fail closed: no NaN cv
    let sq = 0;
    for (let i = 0; i < n; i++) { const d = samples[i] - mean; sq += d * d; }
    const std = Math.sqrt(sq / n); // population stddev
    const cv = std / mean;
    return { median: median(samples), mean, cv, stable: cv < 0.05 };
}

/**
 * True per-op tail latency via process.hrtime.bigint(): time EACH single op call,
 * subtract the calibrated empty-call overhead (an empty `() => {}` measured through
 * the identical hrtime path, median of the same iteration count), and CLAMP at 0 so
 * a reading below the timer's own overhead never reports negative. Returns ns.
 *
 * The per-op samples array is pre-sized so the timed inner loop allocates nothing;
 * hrtime.bigint() itself allocates a BigInt per call, but that is the ONLY portable
 * per-op nanosecond clock in Node and it is charged to BOTH the op and the empty
 * baseline, so it cancels in the subtraction.
 * @param {(i:number) => void} op
 * @param {number} iters  number of single-op timings to take
 * @returns {{p99:number, max:number}} nanoseconds, overhead-subtracted, clamped >= 0
 */
export function perOpTail(op, iters) {
    if (iters <= 0) return { p99: 0, max: 0 };
    // Calibrate the empty-call overhead through the identical hrtime path.
    const noop = () => {};
    const cal = new Float64Array(iters);
    for (let i = 0; i < iters; i++) {
        const t0 = process.hrtime.bigint();
        noop(i);
        const t1 = process.hrtime.bigint();
        cal[i] = Number(t1 - t0);
    }
    cal.sort();
    const overhead = cal[iters >> 1]; // median empty-call cost (ns)

    const s = new Float64Array(iters);
    for (let i = 0; i < iters; i++) {
        const t0 = process.hrtime.bigint();
        op(i);
        const t1 = process.hrtime.bigint();
        let ns = Number(t1 - t0) - overhead;
        if (ns < 0) ns = 0; // clamp: a reading below timer overhead is not negative time
        s[i] = ns;
    }
    s.sort();
    return { p99: percentile(s, 99), max: s[iters - 1] };
}
